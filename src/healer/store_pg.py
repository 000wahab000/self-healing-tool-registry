"""Postgres implementation of FixStore (requires the optional psycopg 3 package)."""

from __future__ import annotations

import json
import time
from collections.abc import Callable

from healer import canonical
from healer.models import (
    AuditEvent,
    ErrorClass,
    Fix,
    FixStatus,
)
from healer.settings import NEG_CACHE_TTL_S, RETIRE_AT_LOSSES
from healer.store import AUDIT_COLS, FIX_COLS, _event, _fix

SCHEMA = """
CREATE TABLE IF NOT EXISTS spec_snapshots (
    spec_hash TEXT PRIMARY KEY, spec TEXT NOT NULL, seen_ms BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS fixes (
    fix_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT NOT NULL, signature TEXT NOT NULL, tool TEXT NOT NULL,
    class TEXT NOT NULL CHECK (class IN ('OK','BUSINESS','E1','E2','E3','E4','E5','E6')),
    request_ops TEXT NOT NULL, response_ops TEXT NOT NULL,
    tier SMALLINT NOT NULL CHECK (tier IN (0,1,2)),
    source TEXT NOT NULL CHECK (source IN ('cache','diff','clue','tiebreak','jev','jev_unavailable')),
    schema_hash TEXT NOT NULL, dsl_version INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('candidate','active','failed','retired')),
    wins INTEGER NOT NULL, losses INTEGER NOT NULL, created_ms BIGINT NOT NULL,
    last_used_ms BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS fixes_one_active_per_fingerprint
    ON fixes (fingerprint) WHERE status = 'active';
CREATE TABLE IF NOT EXISTS heal_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_ms BIGINT NOT NULL, tool TEXT NOT NULL, fingerprint TEXT NOT NULL,
    class TEXT NOT NULL CHECK (class IN ('OK','BUSINESS','E1','E2','E3','E4','E5','E6')),
    raw_code TEXT NOT NULL, tier SMALLINT NOT NULL CHECK (tier IN (0,1,2)),
    path TEXT CHECK (path IS NULL OR path IN ('cache','diff','clue','tiebreak','jev','jev_unavailable')),
    fix_id BIGINT, outcome TEXT NOT NULL CHECK (outcome IN ('RECOVERED','ABORTED','VERIFY_FAILED','NOT_DRIFT')),
    reason TEXT CHECK (reason IS NULL OR reason IN ('NO_CANDIDATE','NO_SAFE_VALUE','LOW_CONFIDENCE','UNSAFE_PATCH','UNSAFE_REPLAY','VERIFY_FAILED','POSTCHECK_FAILED_AFTER_WRITE','KNOWN_UNFIXABLE','DEADLINE','NOT_DRIFT','UNSUPPORTED_CLASS')),
    mttr_ms BIGINT NOT NULL, heal_ms BIGINT NOT NULL, jev_tokens INTEGER NOT NULL,
    llm_tokens INTEGER NOT NULL, raw_error TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS call_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts_ms BIGINT NOT NULL, agent TEXT NOT NULL, run_id TEXT NOT NULL,
    tool TEXT NOT NULL,
    class TEXT NOT NULL CHECK (class IN ('OK','BUSINESS','E1','E2','E3','E4','E5','E6')),
    latency_ms BIGINT NOT NULL
);
"""


class PostgresStore:
    """Synchronous FixStore backed by Postgres; active reads always query committed state."""

    # shortcut: synchronous FixStore blocks callers; upgrade when async store support is introduced.

    def __init__(self, dsn: str, clock: Callable[[], float] = time.time) -> None:
        import psycopg
        from psycopg.rows import dict_row

        self._clock = clock
        self._neg: dict[str, float] = {}
        self._db = psycopg.connect(dsn, row_factory=dict_row)
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(SCHEMA)
        self._db.commit()

    def _now_ms(self) -> int:
        return int(self._clock() * 1000)

    def get_active(self, fp: str) -> Fix | None:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                f"SELECT {FIX_COLS} FROM fixes WHERE fingerprint = %s AND status = %s",
                (fp, FixStatus.active),
            )
            row = cur.fetchone()
        return _fix(row) if row else None

    def get_fix(self, fix_id: int) -> Fix | None:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(f"SELECT {FIX_COLS} FROM fixes WHERE fix_id = %s", (fix_id,))
            row = cur.fetchone()
        return _fix(row) if row else None

    def save_fix(self, fix: Fix) -> int:
        with self._db.transaction(), self._db.cursor() as cur:
            if fix.status is FixStatus.active:
                cur.execute(
                    "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                    (fix.fingerprint,),
                )
                cur.execute(
                    "UPDATE fixes SET status = %s WHERE fingerprint = %s AND status = %s",
                    (FixStatus.retired, fix.fingerprint, FixStatus.active),
                )
            cur.execute(
                "INSERT INTO fixes (fingerprint, signature, tool, class, request_ops, response_ops, tier, source, schema_hash, dsl_version, status, wins, losses, created_ms, last_used_ms) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING fix_id",
                (
                    fix.fingerprint,
                    canonical.dumps(fix.signature),
                    fix.tool,
                    fix.cls,
                    canonical.dumps(fix.request_ops),
                    canonical.dumps(fix.response_ops),
                    fix.tier,
                    fix.source,
                    fix.schema_hash,
                    fix.dsl_version,
                    fix.status,
                    fix.wins,
                    fix.losses,
                    fix.created_ms or self._now_ms(),
                    fix.last_used_ms,
                ),
            )
            fix.fix_id = cur.fetchone()["fix_id"]
        return fix.fix_id

    def record_result(self, fix_id: int, won: bool) -> None:
        col = "wins" if won else "losses"
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                f"UPDATE fixes SET {col} = {col} + 1, last_used_ms = %s WHERE fix_id = %s RETURNING losses",
                (self._now_ms(), fix_id),
            )
            row = cur.fetchone()
            if row and row["losses"] >= RETIRE_AT_LOSSES:
                cur.execute(
                    "UPDATE fixes SET status = %s WHERE fix_id = %s AND status = %s",
                    (FixStatus.retired, fix_id, FixStatus.active),
                )

    def audit(self, event: AuditEvent) -> None:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                "INSERT INTO heal_events (ts_ms,tool,fingerprint,class,raw_code,tier,path,fix_id,outcome,reason,mttr_ms,heal_ms,jev_tokens,llm_tokens,raw_error) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                (
                    event.ts_ms,
                    event.tool,
                    event.fingerprint,
                    event.cls,
                    event.raw_code,
                    event.tier,
                    event.path,
                    event.fix_id,
                    event.outcome,
                    event.reason,
                    event.mttr_ms,
                    event.heal_ms,
                    event.jev_tokens,
                    event.llm_tokens,
                    event.raw_error,
                ),
            )
        self._db.commit()

    def audit_events(self) -> list[AuditEvent]:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(f"SELECT {AUDIT_COLS} FROM heal_events ORDER BY event_id")
            return [_event(row) for row in cur.fetchall()]

    def is_negative(self, fp: str) -> bool:
        return self._neg.get(fp, 0) > self._clock()

    def add_negative(self, fp: str) -> None:
        self._neg[fp] = self._clock() + NEG_CACHE_TTL_S

    def save_spec(self, spec_hash: str, spec: dict) -> None:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                "INSERT INTO spec_snapshots (spec_hash,spec,seen_ms) VALUES (%s,%s,%s) ON CONFLICT (spec_hash) DO NOTHING",
                (spec_hash, canonical.dumps(spec), self._now_ms()),
            )
        self._db.commit()

    def get_spec(self, spec_hash: str) -> dict | None:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                "SELECT spec FROM spec_snapshots WHERE spec_hash = %s", (spec_hash,)
            )
            row = cur.fetchone()
        return json.loads(row["spec"]) if row else None

    def log_call(
        self, agent: str, run_id: str, tool: str, cls: ErrorClass, latency_ms: int
    ) -> None:
        with self._db.cursor() as cur:
            cur.execute(
                "INSERT INTO call_events (ts_ms,agent,run_id,tool,class,latency_ms) VALUES (%s,%s,%s,%s,%s,%s)",
                (self._now_ms(), agent, run_id, tool, cls, latency_ms),
            )
        self._db.commit()

    def call_events(self, after_id: int = 0) -> list[dict]:
        with self._db.transaction(), self._db.cursor() as cur:
            cur.execute(
                "SELECT event_id,ts_ms,agent,run_id,tool,class,latency_ms FROM call_events WHERE event_id > %s ORDER BY event_id",
                (after_id,),
            )
            return cur.fetchall()

    def close(self) -> None:
        self._db.close()


